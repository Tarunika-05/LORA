from segmentation_models_pytorch import Unet
import torch.nn as nn

def create_unet_baseline():
    print("🟡 Creating UNet Baseline (ResNet50 encoder)")

    model = Unet(
        encoder_name="resnet50",
        encoder_weights="imagenet",
        in_channels=11,           # dataset input channels
        classes=11,               # number of segmentation classes
    )
    return model

from peft import LoraConfig, get_peft_model

def create_unet_lora(lora_r=16):
    model = create_unet_baseline()
    print(f"🔷 Adding LoRA adapters with r={lora_r}")

    lora_cfg = LoraConfig(
        r=lora_r,
        lora_alpha=lora_r*2,
        target_modules=[
            "conv1", "conv2", "conv3", "conv4", "downsample.0"
        ],
        lora_dropout=0.1,
        bias="none",
        modules_to_save=["decoder", "segmentation_head"]  # keeping decoder trainable
    )

    model = get_peft_model(model, lora_cfg)
    model.print_trainable_parameters()
    return model

