# Compute class weights
label_counts = Counter()
for _, mask in train_ds:
    valid = mask[mask != -1].flatten()
    label_counts.update(valid.tolist())

total = sum(label_counts.values())
freqs = np.array([label_counts.get(i, 0)/total for i in range(11)])
weights = 1.0 / (freqs + 1e-6)
weights = weights / weights.sum()
class_weights = torch.tensor(weights, dtype=torch.float32).to(device)

# Metrics function
def compute_metrics(preds, labels, num_classes=11):
    if isinstance(preds, torch.Tensor):
        preds = torch.argmax(preds, dim=1).cpu().numpy()
    if isinstance(labels, torch.Tensor):
        labels = labels.cpu().numpy()

    valid = labels != -1
    preds_v = preds[valid]
    labels_v = labels[valid]

    accuracy = (preds_v == labels_v).sum() / labels_v.size
    f1 = f1_score(labels_v, preds_v, average='weighted', zero_division=0)

    present_classes = np.unique(labels_v)
    ious = []
    for cls in present_classes:
        pred_m = (preds_v == cls)
        true_m = (labels_v == cls)
        inter = (pred_m & true_m).sum()
        union = (pred_m | true_m).sum()
        if union > 0:
            ious.append(inter / union)
    mean_iou = np.mean(ious) if len(ious) > 0 else 0.0

    return {'Accuracy': accuracy, 'F1': f1, 'mIoU': mean_iou}



# Training function
def train(model, name, epochs=70, lr=None):
    print(f"\n{'#'*70}\n# {name}\n{'#'*70}\n")

    if lr is None:
        lr = 2e-4 if 'lora' in name.lower() else 5e-5

    opt = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=0.01)
    scheduler = CosineAnnealingLR(opt, T_max=epochs, eta_min=1e-6)
    loss_fn = nn.CrossEntropyLoss(weight=class_weights, ignore_index=-1)
    scaler = GradScaler()

    train_dl = DataLoader(train_ds, batch_size=4, shuffle=True, num_workers=2)
    val_dl = DataLoader(val_ds, batch_size=4, shuffle=False, num_workers=2)

    best_metrics = {'mIoU':0, 'F1':0, 'Accuracy':0}
    t0 = time.time()

    for ep in range(epochs):
        model.train()
        total_loss = 0

        for imgs, masks in train_dl:
            if imgs.dim()==4 and imgs.shape[-1]==11:
                imgs = imgs.permute(0,3,1,2)
            imgs = F.interpolate(imgs, size=(224,224), mode='bilinear', align_corners=False)
            imgs, masks = imgs.float().to(device), masks.long().to(device)

            opt.zero_grad()
            with autocast("cuda"):
                out = model(imgs)
                if out.shape[2:] != masks.shape[1:]:
                    out = F.interpolate(out, masks.shape[1:], mode='bilinear')
                loss = loss_fn(out, masks)

            scaler.scale(loss).backward()
            scaler.step(opt)
            scaler.update()
            total_loss += loss.item()

        scheduler.step()

        # Validation
        model.eval()
        val_metrics = {'mIoU':0, 'F1':0, 'Accuracy':0}
        with torch.no_grad():
            for imgs, masks in val_dl:
                if imgs.dim()==4 and imgs.shape[-1]==11:
                    imgs = imgs.permute(0,3,1,2)
                imgs = F.interpolate(imgs, size=(224,224), mode='bilinear', align_corners=False)
                imgs, masks = imgs.float().to(device), masks.long().to(device)

                with autocast("cuda"):
                    out = model(imgs)
                    if out.shape[2:] != masks.shape[1:]:
                        out = F.interpolate(out, masks.shape[1:], mode='bilinear')

                met = compute_metrics(out, masks)
                for k in val_metrics:
                    val_metrics[k] += met[k]

        for k in val_metrics:
            val_metrics[k] /= len(val_dl)

        print(f"Ep {ep+1:02d} | Loss={total_loss/len(train_dl):.4f} | mIoU={val_metrics['mIoU']:.4f} | "
              f"F1={val_metrics['F1']:.4f} | Acc={val_metrics['Accuracy']:.4f}")

        if val_metrics['mIoU'] > best_metrics['mIoU']:
            best_metrics = val_metrics.copy()
            torch.save(model.state_dict(), f"/content/drive/MyDrive/lora_experiments/{name}_best.pth")

    best_metrics['name'] = name
    best_metrics['time_min'] = (time.time()-t0)/60
    return best_metrics

